"""TSIR -> ASAM OpenSCENARIO DSL 2.x (.osc) text.

Structure: one `serial` block per actor inside a top-level `parallel`. Each TSIR action becomes
`wait <trigger>` + the corresponding standard-library action; `after_action` triggers become
named events (`emit`/`wait @`), so causal chains (e.g. a second cut-in 1 s after the first one
starts) are explicit rather than coincidental.
"""
from __future__ import annotations

from pathlib import Path

from tsf.compile.mapping import odr_position
from tsf.ir.scenario import Scenario

_CAT = {"car": "car", "suv": "car", "van": "van", "truck": "truck", "bus": "bus", "motorcycle": "motorcycle",
        "bicycle": "bicycle", "pedestrian": "pedestrian"}


def _q(v: float, unit: str) -> str:
    return f"{v:g}{unit}"


def _wait(trig) -> str:
    k = trig.kind
    if k == "sim_time":
        return f"wait elapsed({_q(trig.t, 's')})" if trig.t > 0 else ""
    if k == "after_action":
        ev = f"{trig.action_id}_{'started' if trig.on == 'start' else 'done'}"
        delay = f"\n{{ind}}wait elapsed({_q(trig.delay, 's')})" if trig.delay else ""
        return f"wait @{ev}{delay}"
    if k == "distance_to_actor":
        op = "<" if trig.rule == "less" else ">"
        if trig.mode == "euclidean":
            expr = f"{trig.actor}.get_distance(object: {trig.other}, freespace: {str(trig.freespace).lower()})"
        else:
            expr = f"{trig.actor}.get_longitudinal_gap(object: {trig.other}, side: {trig.mode})"
        return f"wait rise({expr} {op} {_q(trig.distance, 'm')})"
    if k == "ttc":
        return f"wait rise({trig.actor}.get_ttc(object: {trig.other}) < {_q(trig.ttc, 's')})"
    if k == "distance_to_stop_line":
        return f"wait rise({trig.actor}.get_distance_to_stop_line() < {_q(trig.distance, 'm')})"
    raise ValueError(k)


def _do(act) -> str:
    t = act.type
    a = act.actor
    if t == "speed_change":
        return f"{a}.change_speed(target: {_q(act.target_speed, 'mps')}, rate_profile: linear, " \
               f"rate_peak: {_q(act.accel, 'mpsps')})"
    if t == "lane_change":
        return f"{a}.change_lane(num_of_lanes: {act.lanes}, side: side_left_right!{act.direction}, " \
               f"shape: sinusoidal, duration: {_q(act.duration, 's')})"
    if t == "cut_in":
        return f"{a}.change_lane(target: {act.target}.lane, shape: sinusoidal, duration: {_q(act.duration, 's')})"
    if t == "lane_offset":
        return f"{a}.drive(duration: {_q(act.duration, 's')}) with:\n{{ind}}    lateral(distance: " \
               f"{_q(abs(act.offset), 'm')}, side_of: {a}.lane.center, side: side_left_right!" \
               f"{'left' if act.offset >= 0 else 'right'}, at: end)"
    if t == "follow":
        return f"{a}.drive() with:\n{{ind}}    keep_time_gap(target: {act.target}, gap: {_q(act.time_gap, 's')})"
    if t == "stop_at_line":
        return f"{a}.stop_at_stop_line(deceleration: {_q(act.decel, 'mpsps')})"
    if t == "brake":
        return f"{a}.change_speed(target: 0mps, rate_profile: linear, rate_peak: {_q(act.decel, 'mpsps')})"
    if t == "cross":
        return f"{a}.walk() with:\n{{ind}}    speed({_q(act.speed, 'mps')})\n{{ind}}    cross_road(side: {act.side})"
    raise ValueError(t)


def emit(sc: Scenario, xodr_name: str | None = None) -> str:
    sid = sc.meta.id
    env = sc.environment
    L = [
        f"# {sc.meta.title}",
        f"# Generated by Tanit Scenario Flywheel from TSIR {sc.tsir_version}; source={sc.meta.source}",
        "import osc.standard.all",
        "",
        f"scenario tsf_{sid}:",
        "    map: map with:",
        f'        keep(it.file == "{xodr_name or sid + ".xodr"}")',
        f"    env: environment with:",
        f'        keep(it.time_of_day == "{env.time_of_day}")',
        f"        keep(it.weather == weather_kind!{env.weather})",
        f"        keep(it.road_surface == road_surface!{env.road_surface})",
    ]
    for a in sc.actors:
        kind = "person" if a.category == "pedestrian" else "vehicle"
        L.append(f"    {a.id}: {kind} with:")
        if kind == "vehicle":
            L.append(f"        keep(it.vehicle_category == vehicle_category!{_CAT[a.category]})")
        l, w, h = a.dims()
        L.append(f"        keep(it.bbox.length == {_q(l, 'm')}) keep(it.bbox.width == {_q(w, 'm')})"
                 f" keep(it.bbox.height == {_q(h, 'm')})")
        L.append(f'        keep(it.color == "{a.color}")')
    events = sorted({f"{x.start.action_id}_{'started' if x.start.on == 'start' else 'done'}"
                     for x in sc.actions if x.start.kind == "after_action"})
    for ev in events:
        L.append(f"    event {ev}")
    L += ["", f"    do parallel(duration: {_q(sc.duration, 's')}, overlap: any):"]
    for a in sc.actors:
        rid, lid, s = odr_position(sc, a.initial)
        L.append(f"        {a.id}_story: serial:")
        ind = " " * 12
        L.append(f"{ind}{a.id}.place(road: {rid}, lane: {lid}, s: {_q(round(s, 2), 'm')}, "
                 f"offset: {_q(a.initial.t_offset, 'm')}, speed: {_q(a.initial_speed, 'mps')})")
        if a.route:
            L.append(f"{ind}{a.id}.set_route(turns: [{', '.join(a.route)}])")
        for x in [x for x in sc.actions if x.actor == a.id]:
            w = _wait(x.start)
            if w:
                L += [ind + ln for ln in w.replace("{ind}", "").split("\n")]
            if f"{x.id}_started" in events:
                L.append(f"{ind}emit {x.id}_started")
            L += [ind + ln.replace("{ind}", "") for ln in _do(x).split("\n")]
            if f"{x.id}_done" in events:
                L.append(f"{ind}emit {x.id}_done")
        L.append(f"{ind}{a.id}.drive()")
    return "\n".join(L) + "\n"


def write(sc: Scenario, path: str | Path, xodr_name: str | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(emit(sc, xodr_name), encoding="utf-8")
    return path
