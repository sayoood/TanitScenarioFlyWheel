import { Check, Copy, Download } from "lucide-react";
import { useMemo, useState } from "react";
import clsx from "clsx";
import { bytes } from "../../lib/format";
import { useArtifactText } from "../../lib/hooks";
import { useApi } from "../../lib/provider";
import type { ArtifactKind, RunDetail } from "../../lib/types";
import { Skeleton } from "../ui/primitives";
import { CodeBlock, type CodeLang } from "./CodeBlock";

const TABS: { kind: ArtifactKind; label: string; ext: string; lang: CodeLang }[] = [
  { kind: "xodr", label: ".xodr", ext: "OpenDRIVE", lang: "xml" },
  { kind: "xosc", label: ".xosc", ext: "OpenSCENARIO 1.3", lang: "xml" },
  { kind: "osc2", label: ".osc", ext: "OpenSCENARIO DSL 2", lang: "osc2" },
  { kind: "package", label: "package.json", ext: "IMDAD package", lang: "json" },
];

export function CodeViewer({ run }: { run: RunDetail }) {
  const { api } = useApi();
  const [kind, setKind] = useState<ArtifactKind>("xosc");
  const [copied, setCopied] = useState(false);
  const tab = TABS.find((t) => t.kind === kind) ?? TABS[0];
  const art = useMemo(() => run.artifacts.find((a) => a.kind === kind), [run.artifacts, kind]);
  const q = useArtifactText(run.id, art?.name);

  const copy = async () => {
    if (!q.data) return;
    try {
      await navigator.clipboard.writeText(q.data);
      setCopied(true);
      setTimeout(() => setCopied(false), 1400);
    } catch {
      /* clipboard unavailable */
    }
  };
  const download = () => {
    if (!art) return;
    if (api.kind === "live") {
      window.open(api.artifactUrl(run.id, art.name), "_blank", "noopener");
      return;
    }
    if (!q.data) return;
    const url = URL.createObjectURL(new Blob([q.data], { type: "text/plain" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = art.name;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div>
      <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
        <div role="tablist" aria-label="Artifact" className="inline-flex gap-1 rounded-[11px] border border-line bg-bg/60 p-0.5">
          {TABS.map((t) => {
            const has = run.artifacts.some((a) => a.kind === t.kind);
            const active = t.kind === kind;
            return (
              <button
                key={t.kind}
                role="tab"
                aria-selected={active}
                disabled={!has}
                onClick={() => setKind(t.kind)}
                title={has ? t.ext : `${t.ext}: not generated yet`}
                className={clsx("mono h-8 rounded-[9px] px-3 text-[12.5px] font-medium transition-colors disabled:cursor-not-allowed disabled:opacity-35", active ? "border border-line-2 bg-bg-3 text-fg" : "border border-transparent text-fg-2 hover:text-fg")}
              >
                {t.label}
              </button>
            );
          })}
        </div>
        <div className="flex items-center gap-2">
          {art && (
            <span className="text-[12px] text-fg-2">
              {art.name} · {bytes(art.size)}
              {q.data ? ` · ${q.data.split("\n").length} lines` : ""}
            </span>
          )}
          <button className="btn btn-sm" onClick={copy} disabled={!q.data} aria-label="Copy to clipboard">
            {copied ? <Check size={14} className="text-ok" /> : <Copy size={14} />} {copied ? "Copied" : "Copy"}
          </button>
          <button className="btn btn-sm" onClick={download} disabled={!art} aria-label="Download">
            <Download size={14} /> Download
          </button>
        </div>
      </div>
      {!art ? (
        <div className="rounded-xl border border-dashed border-line-2 p-8 text-center text-[13px] text-fg-2">{tab.ext} is generated by the Document stage after verification passes.</div>
      ) : q.isLoading ? (
        <Skeleton className="h-72" />
      ) : q.isError ? (
        <div className="rounded-xl border border-bad/40 bg-bad/10 p-4 text-[13px] text-bad" role="alert">
          Could not load {art.name}: {(q.error as Error).message}
        </div>
      ) : (
        <CodeBlock code={q.data ?? ""} lang={tab.lang} label={`${tab.ext} source`} />
      )}
    </div>
  );
}
